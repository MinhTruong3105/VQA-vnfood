            # SỬ DỤNG base_model THAY VÌ model
            h_d, c_d, features = base_model(img_tensor, input_ids, attention_mask)
            current_word_idx = torch.tensor([vocab.stoi["<SOS>"]]).to(device)
            pred_words = []

            for _ in range(max_len):
                # SỬ DỤNG base_model THAY VÌ model
                context, _ = base_model.attention(features, h_d[0])
