               # 0.5 = lấy khi AI đúng < 50% số từ so với ground truth

# ── 2. HÀM TIỆN ÍCH ──────────────────────────────────────────────────────────
def token_overlap_ratio(pred: str, ref: str) -> float:
    """
    Tỉ lệ từ trùng giữa pred và ref (Precision phía pred).
    = |{từ trong pred} ∩ {từ trong ref}| / max(|pred|, 1)
    """
    pred_tokens = set(pred.lower().split())
    ref_tokens  = set(ref.lower().split())
    if not pred_tokens:
        return 0.0
    return len(pred_tokens & ref_tokens) / len(pred_tokens)

def is_wrong(pred: str, ref: str, threshold: float = SIMILARITY_THR) -> bool:
    """Trả về True nếu câu trả lời của AI bị coi là sai/không đủ tốt."""
    if not pred or pred.strip() == "(không có câu trả lời)":
        return True
    return token_overlap_ratio(pred, ref) < threshold

