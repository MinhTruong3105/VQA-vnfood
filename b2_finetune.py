def parse_vqa_json(json_path, img_folder):
    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    flattened_data = []
    for item in data:
        image_id = item['image_id']
        # Kiểm tra phần mở rộng file (jpg/png) tùy dataset của bạn
