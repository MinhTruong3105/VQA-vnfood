class VQAMonAnDataset(Dataset):
    def __init__(self, dataframe, processor, max_length=64):
        self.df          = dataframe.reset_index(drop=True)
        self.processor   = processor
        self.max_length  = max_length

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        img_path = row['image_path']

        try:
            image = Image.open(img_path).convert('RGB')
        except Exception as e:
            image = Image.new('RGB', (224, 224), (180, 180, 180))

        # Lấy trực tiếp câu tiếng Anh đã dịch sẵn
        question_en = str(row['question_en'])
        answer_en   = str(row['answer_en'])

        prompt = f"Question: {question_en}\nAnswer: {answer_en}"

        # ── Encode ────────────────────────────────────────────────────────────
        encoding = self.processor(
            images=image,
            text=prompt,
            return_tensors="pt",
            padding="max_length",
            max_length=self.max_length,
            truncation=True,
        )

        pixel_values = encoding['pixel_values'].squeeze(0)
        input_ids    = encoding['input_ids'].squeeze(0)

        # ── Tạo labels để tính loss ──────────────────────────────────────────
        labels = input_ids.clone()
        answer_token = self.processor.tokenizer.encode("Answer:", add_special_tokens=False)
        answer_pos = -1

        for i in range(len(input_ids) - len(answer_token)):
            if input_ids[i: i + len(answer_token)].tolist() == answer_token:
                answer_pos = i + len(answer_token)
                break

        if answer_pos > 0:
            labels[:answer_pos] = -100  # Mask phần prompt + câu hỏi

        # Mask padding tokens
        labels[labels == self.processor.tokenizer.pad_token_id] = -100

        return {
            'pixel_values': pixel_values,
            'input_ids':    input_ids,
            'labels':       labels,
        }


