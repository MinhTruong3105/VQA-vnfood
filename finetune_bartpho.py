def load_and_split_dataset(config: Config) -> DatasetDict:
    with open(config.data_path, 'r', encoding='utf-8') as f:
        raw_data = json.load(f)

    processed = [
        {'article': item['document'], 'summary': item['summary']}
        for item in raw_data
        if item.get('document') and item.get('summary')
    ]

    full_dataset = Dataset.from_list(processed)

    train_val = full_dataset.train_test_split(
        test_size=config.test_ratio, seed=config.seed
    )
    val_ratio_adjusted = config.val_ratio / (config.train_ratio + config.val_ratio)
    train_val_split = train_val['train'].train_test_split(
        test_size=val_ratio_adjusted, seed=config.seed
    )

    return DatasetDict({
        'train':      train_val_split['train'],
        'validation': train_val_split['test'],
        'test':       train_val['test'],
    })


