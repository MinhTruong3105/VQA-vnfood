"""## 3. Tokenization

- **Input:** truncate đến `max_input_length=1024`, padding=False (DataCollator xử lý dynamic padding).
- **Target:** dùng `text_target` để BARTpho áp dụng đúng special tokens cho decoder side.
- **Labels:** padding được thay bằng `-100` bởi DataCollator để không đóng góp vào loss.
"""

tokenizer = AutoTokenizer.from_pretrained(cfg.model_name, use_fast=True)


def build_preprocess_function(tokenizer, config: Config):
    def preprocess_function(examples: dict) -> dict:
        model_inputs = tokenizer(
            examples['article'],
            max_length=config.max_input_length,
            truncation=True,
            padding=False,
        )
        labels = tokenizer(
            text_target=examples['summary'],
            max_length=config.max_target_length,
            truncation=True,
            padding=False,
        )
        model_inputs['labels'] = labels['input_ids']
        return model_inputs
    return preprocess_function


