"""## 4. Evaluation — ROUGE Metrics

**ROUGE** (Lin, 2004) đo mức trùng lặp n-gram giữa hypothesis và reference.
Là tiêu chuẩn đánh giá summarization trong các benchmark CNN/DailyMail, XSum, ViNewsSum.

| Metric | Đo lường |
|---|---|
| ROUGE-1 | Overlap unigram — coverage từ vựng |
| ROUGE-2 | Overlap bigram — mạch lạc cục bộ |
| ROUGE-L | Longest Common Subsequence — cấu trúc câu |
| ROUGE-Lsum | ROUGE-L per sentence, phù hợp output nhiều câu |

> **Hạn chế:** ROUGE không đo semantic similarity.
"""

rouge_metric = evaluate.load('rouge')


def build_compute_metrics(tokenizer, config: Config):
    def compute_metrics(eval_preds) -> dict:
        predictions, labels = eval_preds

        if isinstance(predictions, tuple):
            predictions = predictions[0]

        # Cả predictions lẫn labels đều có thể chứa -100 (padding của Trainer).
        # BARTpho tokenizer không decode được -100 -> replace về pad_token_id trước.
        predictions = predictions.tolist() if hasattr(predictions, 'tolist') else predictions
        predictions = [
            [t if t != -100 else tokenizer.pad_token_id for t in pred]
            for pred in predictions
        ]

        labels = labels.tolist() if hasattr(labels, 'tolist') else labels
        labels = [
            [t if t != -100 else tokenizer.pad_token_id for t in label]
            for label in labels
        ]

        decoded_preds = tokenizer.batch_decode(
            predictions,
            skip_special_tokens=True,
            clean_up_tokenization_spaces=True,
        )
        decoded_labels = tokenizer.batch_decode(
            labels,
            skip_special_tokens=True,
            clean_up_tokenization_spaces=True,
        )

        decoded_preds  = [p.strip() for p in decoded_preds]
        decoded_labels = [l.strip() for l in decoded_labels]

        result = rouge_metric.compute(
            predictions=decoded_preds,
            references=decoded_labels,
            use_stemmer=False,
            use_aggregator=True,
        )
        result = {k: round(v * 100, 4) for k, v in result.items()}

        pred_lens = [
            sum(1 for t in pred if t != tokenizer.pad_token_id)
            for pred in predictions
        ]
        result['gen_len'] = round(sum(pred_lens) / len(pred_lens), 2)

        return result

    return compute_metrics


