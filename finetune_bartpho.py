def summarize(text: str, model_path: str, config: Config = None) -> dict:
    if config is None:
        config = Config()

    _device = 'cuda' if torch.cuda.is_available() else 'cpu'
    _tok    = AutoTokenizer.from_pretrained(model_path)
    _model  = AutoModelForSeq2SeqLM.from_pretrained(model_path).eval().to(_device)

    inputs = _tok(
        text,
        max_length=config.max_input_length,
        truncation=True,
        return_tensors='pt',
    ).to(_device)

    with torch.no_grad():
        output_ids = _model.generate(
            **inputs,
            max_new_tokens=config.max_target_length,
            num_beams=config.num_beams,
            length_penalty=config.length_penalty,
            no_repeat_ngram_size=config.no_repeat_ngram_size,
            early_stopping=True,
        )

    summary = _tok.decode(
        output_ids[0],
        skip_special_tokens=True,
        clean_up_tokenization_spaces=True,
    )
    return {
        'summary':       summary.strip(),
        'input_tokens':  inputs['input_ids'].shape[1],
        'output_tokens': output_ids.shape[1],
    }


